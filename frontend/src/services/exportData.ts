// Files the user can take away. Values are copied from the API response as they are: nothing is recomputed.
import type { RainfallSeriesResponse } from '../types/api'

export const DEMO_WARNING = 'DEMO DATA: synthetic rainfall, not NASA. Do not quote.'

/** Annual totals as CSV, with the source in comment lines at the top. */
export function annualCsv(series: RainfallSeriesResponse): string {
  const p = series.provenance
  const head = [
    `# MboaScope annual rainfall, ${series.box_label}, ${series.period[0]} to ${series.period[1]}`,
    `# Source: ${p.dataset}, doi:${p.doi}. Satellite estimates averaged over the box, not point readings.`,
    `# Years with missing months are marked complete=false and are not used in the trend tests.`,
    ...(series.is_mock ? [`# ${DEMO_WARNING}`] : []),
    `# Generated by the API at ${series.generated_at}`,
    'year,total_mm,months_present,complete',
  ]
  const rows = series.years.map((y) => `${y.year},${y.total_mm},${y.months_present},${y.complete}`)
  return [...head, ...rows].join('\n') + '\n'
}

/** A safe file name such as mboascope_garoua_2001-2024. */
export function fileStem(regionId: string, start: number, end: number): string {
  return `mboascope_${regionId.replace(/[^a-z0-9_-]/gi, '')}_${start}-${end}`
}

export function downloadBlob(blob: Blob, filename: string): void {
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = filename
  document.body.appendChild(a)
  a.click()
  a.remove()
  setTimeout(() => URL.revokeObjectURL(url), 1000)
}

const STYLE_PROPS = ['fill', 'fill-opacity', 'stroke', 'stroke-width', 'stroke-dasharray', 'stroke-opacity', 'opacity', 'font-size', 'font-family', 'font-weight']

/**
 * Turn a chart's SVG into a PNG. CSS variables do not survive serialisation, so the computed
 * colours are copied onto each element first. A caption with the source (and the demo warning) is added.
 */
export async function svgToPng(svg: SVGSVGElement, caption: string[], scale = 2): Promise<Blob> {
  const { width, height } = svg.getBoundingClientRect()
  const clone = svg.cloneNode(true) as SVGSVGElement
  const src = svg.querySelectorAll('*')
  const dst = clone.querySelectorAll('*')
  src.forEach((el, i) => {
    const cs = getComputedStyle(el)
    const target = dst[i] as SVGElement
    for (const prop of STYLE_PROPS) {
      const v = cs.getPropertyValue(prop)
      if (v) target.style.setProperty(prop, v)
    }
  })
  clone.setAttribute('xmlns', 'http://www.w3.org/2000/svg')
  clone.setAttribute('width', String(width))
  clone.setAttribute('height', String(height))
  const data = new XMLSerializer().serializeToString(clone)
  const img = new Image()
  img.src = 'data:image/svg+xml;charset=utf-8,' + encodeURIComponent(data)
  await img.decode()

  const pad = 24
  const lineH = 18
  const font = '12px system-ui, sans-serif'
  const canvas = document.createElement('canvas')
  const ctx = canvas.getContext('2d')
  if (!ctx) throw new Error('Canvas is not available in this browser.')
  // Wrap the caption to the chart width.
  ctx.font = font
  const lines: string[] = []
  for (const text of caption) {
    if (text === DEMO_WARNING) {
      lines.push(text) // never split the warning
      continue
    }
    let line = ''
    for (const word of text.split(' ')) {
      const next = line ? `${line} ${word}` : word
      if (line && ctx.measureText(next).width > width) {
        lines.push(line)
        line = word
      } else line = next
    }
    lines.push(line)
  }
  canvas.width = (width + pad * 2) * scale
  canvas.height = (height + pad * 2 + lines.length * lineH) * scale
  ctx.scale(scale, scale)
  const bg = getComputedStyle(document.documentElement).getPropertyValue('--surface-solid').trim() || '#0b1f19'
  ctx.fillStyle = bg
  ctx.fillRect(0, 0, canvas.width, canvas.height)
  ctx.drawImage(img, pad, pad, width, height)
  ctx.font = font
  lines.forEach((line, i) => {
    ctx.fillStyle = line === DEMO_WARNING ? '#f3d27a' : '#b6cbc1'
    ctx.fillText(line, pad, pad + height + 14 + i * lineH)
  })
  return new Promise((resolve, reject) => canvas.toBlob((b) => (b ? resolve(b) : reject(new Error('Image export failed.'))), 'image/png'))
}

/** Copy text; falls back to a hidden text area where the Clipboard API is blocked. */
export async function copyText(text: string): Promise<void> {
  try {
    await navigator.clipboard.writeText(text)
  } catch {
    const area = document.createElement('textarea')
    area.value = text
    area.setAttribute('readonly', '')
    area.style.position = 'fixed'
    area.style.opacity = '0'
    document.body.appendChild(area)
    area.select()
    const ok = document.execCommand('copy')
    area.remove()
    if (!ok) throw new Error('Copy is blocked by this browser.')
  }
}
